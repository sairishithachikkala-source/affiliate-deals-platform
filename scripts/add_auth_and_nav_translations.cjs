const translationsDir = path.resolve(__dirname, '../src/i18n/translations');

for (const [lang, keys] of Object.entries(newTranslations)) {
  const filePath = path.join(translationsDir, `${lang}.json`);
  if (fs.existsSync(filePath)) {
    const raw = fs.readFileSync(filePath, 'utf8');
    const json = JSON.parse(raw);
    const updated = { ...json, ...keys };
    fs.writeFileSync(filePath, JSON.stringify(updated, null, 2), 'utf8');
    console.log(`Updated translations for ${lang}: added ${Object.keys(keys).length} keys`);
  }
}
